package dev.taskbarhero.engine

/**
 * Pixel art as palette-indexed string art: '.' is transparent, '1'..'9' index the
 * sprite's own colour list. Every fighter carries its outline as index 1, which
 * is what keeps a 12-pixel sprite readable against dungeon stone.
 *
 * Authoring here rather than in PNGs is deliberate: the art is diffable, it stays
 * in the pure module, and a unit test can assert every row is square and every
 * index has a colour.
 */
object Sprites {

    /**
     * Every fighter is drawn on the same 32x32 grid, so one integer scale factor
     * serves all of them. Non-integer scaling is what makes pixel art mushy — it
     * drops source pixels — so a bigger boss means a busier 32x32, never a bigger
     * canvas.
     *
     * The art is generated rather than typed: shapes are laid down and a one-pixel
     * outline is grown around the silhouette. Hand-typing 32 rows of 32 characters
     * per sprite is not a plan, and the outline pass is what keeps a fighter
     * readable against lit masonry.
     */
    const val FIGHTER_SIZE = 32

    private const val OUTLINE = 0xFF14101A.toInt()
    private const val BONE = 0xFFEDE6D2.toInt()
    private const val GOLD = 0xFFF2B233.toInt()
    private const val GOLD_DARK = 0xFF8C6218.toInt()
    private const val GOLD_LIT = 0xFFF8E08A.toInt()

    class Art(val rows: List<String>, private val colors: IntArray) {
        val size: Int get() = rows.size

        /** Colour of a cell, or null where the sprite is transparent. */
        fun colorAt(x: Int, y: Int): Int? {
            val c = rows[y][x]
            if (c == '.') return null
            return colors[c - '1']
        }

        internal val paletteSize: Int get() = colors.size
    }

    fun of(key: SpriteKey): Art = ART.getValue(key)

    fun icon(key: IconKey): Art = ICONS.getValue(key)

    /**
     * The pose a hero holds right now: a grave while down, and for the knight a
     * swing every other half-second, driven by the wall clock so every redraw
     * agrees on it.
     *
     * This is the *key*, not the art, because a dropped-in sheet has to follow the
     * same beat as the built-in sprites — otherwise the knight would swing only
     * when the player has no sprite pack.
     */
    fun heroKey(cls: HeroClass, nowMs: Long, down: Boolean = false): SpriteKey = when {
        down -> SpriteKey.GRAVE
        cls == HeroClass.KNIGHT && (nowMs / 500L) % 2L != 0L -> SpriteKey.KNIGHT_SWING
        else -> cls.sprite
    }

    fun heroFrame(cls: HeroClass, nowMs: Long, down: Boolean = false): Art =
        of(heroKey(cls, nowMs, down))

